const modal = document.getElementById("cv-modal");
const modalContent = document.getElementById("cv-modal-content");
const modalClose = document.getElementById("cv-modal-close");
let activeCard = null;

function escapeHtml(value) {
  const element = document.createElement("div");
  element.textContent = value;
  return element.innerHTML;
}

function renderTimeline(items) {
  return items.map(([date, title, detail]) => `
    <div class="cv-entry">
      <p class="cv-entry__date">${escapeHtml(date)}</p>
      <div><h4>${escapeHtml(title)}</h4><p>${escapeHtml(detail)}</p></div>
    </div>
  `).join("");
}

function renderSection(title, body, wide = false) {
  return `<section class="cv-section${wide ? " cv-section--wide" : ""}">
    <h3>${escapeHtml(title)}</h3>${body}
  </section>`;
}

function openCv(memberId, card) {
  const member = members[memberId];
  if (!member || !modal || !modalContent) return;

  activeCard = card;
  modalContent.innerHTML = `
    <header class="cv-profile">
      <div class="cv-profile__identity">
        <p class="cv-profile__eyebrow">Curriculum vitae</p>
        <h2 id="cv-modal-name">${escapeHtml(member.name)}</h2>
        <p class="cv-profile__role">${escapeHtml(member.role)}</p>
      </div>
      <div class="cv-profile__aside">
        <div class="cv-profile__links" aria-label="Contact links">
          <a href="mailto:${member.email}">${escapeHtml(member.email)}</a>
          <a href="${member.linkedin}" target="_blank" rel="noopener noreferrer">LinkedIn profile</a>
        </div>
        <img src="${member.image}" alt="Portrait of ${escapeHtml(member.name)}" class="cv-profile__photo">
      </div>
    </header>
    <div class="cv-layout">
      ${renderSection("Summary statement", `<p class="cv-summary">${escapeHtml(member.summary)}</p>`, true)}
      ${renderSection("Education", renderTimeline(member.education))}
      ${renderSection("Work experience", renderTimeline(member.work))}
      ${renderSection("Research experience", renderTimeline(member.research))}
      ${renderSection("Skills & competencies", `<ul class="cv-skill-list">${member.skills.map((skill) => `<li>${escapeHtml(skill)}</li>`).join("")}</ul>`)}
      ${renderSection("Affiliations", renderTimeline(member.affiliations))}
    </div>
  `;

  modal.showModal();
}

document.querySelectorAll("[data-cv-member]").forEach((card) => {
  card.addEventListener("click", (event) => {
    if (event.target.closest("a, button")) return;
    openCv(card.dataset.cvMember, card);
  });

  card.addEventListener("keydown", (event) => {
    if (event.target !== card || (event.key !== "Enter" && event.key !== " ")) return;
    event.preventDefault();
    openCv(card.dataset.cvMember, card);
  });
});

modalClose?.addEventListener("click", () => modal?.close());

modal?.addEventListener("click", (event) => {
  if (event.target === modal) modal.close();
});

modal?.addEventListener("close", () => {
  activeCard?.focus();
  activeCard = null;
});
